const reverseUuidMap: Record<string, string> = {};
for (const [key, value] of Object.entries(uuidMap)) {
  reverseUuidMap[value] = key;
}

export function toUUID(id: string): string {
  if (!id) return id;
  return uuidMap[id as keyof typeof uuidMap] || id;
}

export function fromUUID(uuid: string): string {
  if (!uuid) return uuid;
  return reverseUuidMap[uuid] || uuid;
}
